"""
STEP 1 + 2: Pull sector ETF price data, then test candidate pairs for cointegration.

Cointegration = a statistical test that tells us whether two price series have a
*stable long-run relationship* (they tend to drift back toward each other over time)
rather than just being randomly correlated in the short term.

Run this locally: pip install yfinance statsmodels pandas numpy matplotlib
"""

import yfinance as yf
import pandas as pd
import numpy as np
from statsmodels.tsa.stattools import coint
import matplotlib.pyplot as plt

# ---------------------------------------------------------
# STEP 1: Pull data
# ---------------------------------------------------------

# Candidate pairs to test — sectors that are economically linked
CANDIDATE_PAIRS = [
    ("XLE", "XLB"),  # Energy vs Materials (both commodity-sensitive) <------ we will advance with these etf's
    ("XLF", "XLI"),  # Financials vs Industrials
    ("XLU", "XLP"),  # Utilities vs Staples (both "defensive" sectors)
    ("XLK", "XLY"),  # Tech vs Consumer Discretionary
]

# Flatten to a unique list of tickers we need to download
all_tickers = sorted(set(t for pair in CANDIDATE_PAIRS for t in pair))

print(f"Pulling 5 years of daily data for: {all_tickers}")

# yfinance downloads all tickers at once and returns a multi-column DataFrame
raw = yf.download(all_tickers, period="5y", auto_adjust=True)["Close"]

# Drop any rows with missing data (e.g. holidays where one ticker didn't trade)
prices = raw.dropna()

print(f"\nData shape: {prices.shape[0]} trading days x {prices.shape[1]} tickers")
print(prices.head())

# Save so we don't have to re-download every time we run the script
prices.to_csv("sector_etf_prices.csv")
print("\nSaved to sector_etf_prices.csv")

# ---------------------------------------------------------
# STEP 2: Test each candidate pair for cointegration
# ---------------------------------------------------------

print("\n" + "=" * 60)
print("COINTEGRATION TEST RESULTS")
print("=" * 60)

results = []

for ticker_a, ticker_b in CANDIDATE_PAIRS:
    series_a = prices[ticker_a]
    series_b = prices[ticker_b]

    # coint() returns: test statistic, p-value, critical values
    # p-value < 0.05 is the conventional cutoff for "likely cointegrated"
    score, pvalue, _ = coint(series_a, series_b)

    results.append({
        "pair": f"{ticker_a}/{ticker_b}",
        "p_value": round(pvalue, 4),
        "likely_cointegrated": pvalue < 0.05
    })

    print(f"{ticker_a}/{ticker_b}: p-value = {pvalue:.4f} "
          f"{'<-- COINTEGRATED' if pvalue < 0.05 else ''}")

results_df = pd.DataFrame(results)
print("\nSummary:")
print(results_df)

# ---------------------------------------------------------
# Plot the price ratio for each pair so you can eyeball mean reversion
# ---------------------------------------------------------

fig, axes = plt.subplots(len(CANDIDATE_PAIRS), 1, figsize=(10, 12))

for ax, (ticker_a, ticker_b) in zip(axes, CANDIDATE_PAIRS):
    ratio = prices[ticker_a] / prices[ticker_b]
    ax.plot(ratio.index, ratio.values)
    ax.axhline(ratio.mean(), color="red", linestyle="--", alpha=0.7, label="mean")
    ax.set_title(f"{ticker_a}/{ticker_b} price ratio")
    ax.legend()

plt.tight_layout()
plt.savefig("pair_ratios.png", dpi=120)
print("\nSaved ratio plots to pair_ratios.png")
plt.show()

"""
STEP 2b: Two follow-up analyses based on what we learned from the broad sector ETFs.

PART A: Rolling cointegration test on XLE/XLB
  Instead of one p-value for all 5 years, we test cointegration on a rolling window
  (e.g. the trailing 252 trading days = ~1 year) and slide it forward day by day.
  This shows us WHEN the relationship was actually reliable vs. when it broke down —
  which is exactly the kind of signal we'll need for labeling "revert vs break" later.

PART B: Test more granular pairs
  Broad sector ETFs are noisy because they average dozens of companies together.
  Same-industry single stocks or subsector ETFs often share more direct business
  drivers, so they may cointegrate more cleanly.

Run this locally: pip install yfinance statsmodels pandas numpy matplotlib
"""

