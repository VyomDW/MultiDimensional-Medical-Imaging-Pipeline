# PART A: Rolling cointegration on XLE/XLB
# ---------------------------------------------------------

print("Loading previously saved price data...")
prices = pd.read_csv("sector_etf_prices.csv", index_col="Date", parse_dates=True)

WINDOW = 252  # ~1 trading year
STEP = 5      # slide the window forward 5 trading days at a time (faster, still smooth)

series_a = prices["XLE"]
series_b = prices["XLB"]

rolling_dates = []
rolling_pvalues = []

for start in range(0, len(prices) - WINDOW, STEP):
    end = start + WINDOW
    window_a = series_a.iloc[start:end]
    window_b = series_b.iloc[start:end]

    _, pvalue, _ = coint(window_a, window_b)

    rolling_dates.append(prices.index[end - 1])  # label with the window's last date
    rolling_pvalues.append(pvalue)

rolling_df = pd.DataFrame({"date": rolling_dates, "p_value": rolling_pvalues})
rolling_df.to_csv("xle_xlb_rolling_cointegration.csv", index=False)

pct_reliable = (rolling_df["p_value"] < 0.05).mean() * 100
print(f"\nXLE/XLB was cointegrated (p < 0.05) in {pct_reliable:.1f}% of rolling 1-year windows")

