fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=True)

ratio = series_a / series_b
ax1.plot(prices.index, ratio.values)
ax1.axhline(ratio.mean(), color="red", linestyle="--", alpha=0.5, label="5yr mean")
ax1.set_title("XLE/XLB price ratio")
ax1.legend()

ax2.plot(rolling_df["date"], rolling_df["p_value"])
